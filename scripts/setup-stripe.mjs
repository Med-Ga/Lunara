// Creates (or reuses) the LUNARA test-mode prices and writes supabase/seed.sql.
// Usage: node --env-file=.env scripts/setup-stripe.mjs
import Stripe from "stripe";
import { writeFileSync } from "node:fs";

const key = process.env.STRIPE_SECRET_KEY ?? "";
if (!key.startsWith("sk_test_")) {
  console.error("STRIPE_SECRET_KEY must be a TEST key (sk_test_...). Aborting.");
  process.exit(1);
}
const stripe = new Stripe(key);

// Linear per-minute pricing in USD cents: Mars $10/min, Moon $7/min. Durations 1 / 5 / 10 min.
const RATES = { mars: 1000, moon: 700 };
const NAMES = { mars: "Mars", moon: "Moon" };
const MINUTES = [1, 5, 10];
const currency = "usd";

const rows = [];
const ids = [];
let sort = 0;
for (const dest of ["mars", "moon"]) {
  for (const minutes of MINUTES) {
    const id = `${dest}-${minutes}m`;
    const amount = RATES[dest] * minutes;
    const lookup = `lunara_${id}_${amount}_${currency}`;
    let price = (await stripe.prices.list({ lookup_keys: [lookup], active: true, limit: 1 })).data[0];
    if (!price) {
      const product = await stripe.products.create({
        name: `LUNARA ${NAMES[dest]} — ${minutes} min simulated exploration`,
        metadata: { lunara_package: id, lunara_destination: dest },
      });
      price = await stripe.prices.create({
        product: product.id,
        unit_amount: amount,
        currency,
        lookup_key: lookup,
        metadata: { lunara_package: id, lunara_destination: dest },
      });
      console.log(`created ${id}: ${price.id}`);
    } else {
      console.log(`reusing ${id}: ${price.id}`);
    }
    if (price.livemode || price.unit_amount !== amount || price.currency !== currency) {
      throw new Error(`Price ${price.id} does not match ${id}`);
    }
    const label = `${minutes} ${minutes === 1 ? "minute" : "minutes"}`;
    rows.push(`('${id}', '${dest}', '${label}', ${minutes * 60000}, ${amount}, '${currency}', '${price.id}', true, ${++sort})`);
    ids.push(`'${id}'`);
  }
}

const sql = `-- Generated by scripts/setup-stripe.mjs (Stripe TEST mode). Safe to re-run.
-- Legacy packages are deactivated, never deleted: historical purchases keep their snapshots.
insert into public.packages (id, destination_id, label, duration_ms, amount_minor, currency, stripe_price_id, active, sort_order)
values
  ${rows.join(",\n  ")}
on conflict (id) do update set
  label = excluded.label, stripe_price_id = excluded.stripe_price_id,
  active = excluded.active, sort_order = excluded.sort_order
  where public.packages.duration_ms = excluded.duration_ms
    and public.packages.amount_minor = excluded.amount_minor
    and public.packages.currency = excluded.currency
    and public.packages.destination_id = excluded.destination_id;
update public.packages set active = false where id not in (${ids.join(", ")});
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql");
