// Creates (or reuses) the LUNARA test-mode products/prices and writes supabase/seed.sql.
// Usage: node --env-file=.env scripts/setup-stripe.mjs
import Stripe from "stripe";
import { writeFileSync } from "node:fs";

const key = process.env.STRIPE_SECRET_KEY ?? "";
if (!key.startsWith("sk_test_")) {
  console.error("STRIPE_SECRET_KEY must be a TEST key (sk_test_...). Aborting.");
  process.exit(1);
}
const stripe = new Stripe(key);

// Proposed catalog (PRODUCT.md §B, OD-02): 1 / 5 / 15 minutes at EUR 1 / 4 / 10.
const catalog = [
  { id: "demo-pass", label: "Demo Pass", minutes: 1, amount: 100, sort: 1 },
  { id: "explorer", label: "Explorer", minutes: 5, amount: 400, sort: 2 },
  { id: "horizon", label: "Horizon", minutes: 15, amount: 1000, sort: 3 },
];
const currency = "eur";

const rows = [];
for (const p of catalog) {
  const lookup = `lunara_${p.id}_${p.amount}_${currency}`;
  let price = (await stripe.prices.list({ lookup_keys: [lookup], active: true, limit: 1 })).data[0];
  if (!price) {
    const product = await stripe.products.create({
      name: `LUNARA ${p.label} — ${p.minutes} min simulated exploration`,
      metadata: { lunara_package: p.id },
    });
    price = await stripe.prices.create({
      product: product.id,
      unit_amount: p.amount,
      currency,
      lookup_key: lookup,
      metadata: { lunara_package: p.id },
    });
    console.log(`created ${p.id}: ${price.id}`);
  } else {
    console.log(`reusing ${p.id}: ${price.id}`);
  }
  if (price.livemode) throw new Error("Refusing live-mode price");
  rows.push(
    `('${p.id}', '${p.label}', ${p.minutes * 60000}, ${p.amount}, '${currency}', '${price.id}', true, ${p.sort})`,
  );
}

const sql = `-- Generated by scripts/setup-stripe.mjs (Stripe TEST mode). Safe to re-run.
insert into public.packages (id, label, duration_ms, amount_minor, currency, stripe_price_id, active, sort_order)
values
  ${rows.join(",\n  ")}
on conflict (id) do update set
  label = excluded.label, stripe_price_id = excluded.stripe_price_id,
  active = excluded.active, sort_order = excluded.sort_order
  where public.packages.duration_ms = excluded.duration_ms
    and public.packages.amount_minor = excluded.amount_minor
    and public.packages.currency = excluded.currency;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql");
